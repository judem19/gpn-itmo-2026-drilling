# --- Загрузка датасета и временных разрывов ---
df = pd.read_csv(RAW_PATH)
df["Time"] = pd.to_datetime(df["Time"], format="%d.%m.%Y %H:%M:%S")
df = df.sort_values("ID").reset_index(drop=True)
N = len(df)
dt = df["Time"].diff().dt.total_seconds().fillna(5.0).to_numpy()

# Центрированная скорость без перескока через разрывы dt > 10 сек
def get_centered_slope(arr, half_w, dt_arr, gap_thr=10.0):
    cuts = np.where(dt_arr > gap_thr)[0]
    bounds = np.r_[0, cuts, len(arr)]
    res = np.zeros(len(arr), dtype=np.float32)
    for a, b in zip(bounds[:-1], bounds[1:]):
        seg = arr[a:b]
        n = len(seg)
        if n <= 2:
            continue
        idx = np.arange(n)
        lo = np.maximum(0, idx - half_w)
        hi = np.minimum(n - 1, idx + half_w)
        res[a:b] = (seg[hi] - seg[lo]) / np.maximum(hi - lo, 1)
    return res

# Очищенные датчики
bp    = np.clip(df["BitPosition"].to_numpy(dtype=np.float32), 0.0, None)
rop   = np.clip(df["ROP"].to_numpy(dtype=np.float32), 0.0, None)
flow  = np.clip(df["InletFlow"].to_numpy(dtype=np.float32), 0.0, None)
pres  = np.clip(df["ManifoldPressure"].to_numpy(dtype=np.float32), 0.0, None)
rot   = np.clip(df["Turn_rotor"].to_numpy(dtype=np.float32), 0.0, None)
wedge = np.clip(df["WedgePosition"].to_numpy(dtype=np.float32), 0.0, 1.5)
hl    = np.clip(df["HL"].to_numpy(dtype=np.float32), 0.0, None)
load  = np.clip(df["Load"].to_numpy(dtype=np.float32), 0.0, None)
bit_sl = np.clip(get_centered_slope(bp, 12, dt), -5.0, 5.0)

# Физическая матрица и реальные скачки датчиков
X_eval = np.column_stack([bp, rop, flow, pres, rot, wedge, hl, load])
X_eval = np.clip(StandardScaler().fit_transform(X_eval), -6.0, 6.0).astype(np.float32)
tot_var = float(np.var(X_eval, axis=0).sum())

jump_step = np.zeros(N, dtype=np.float32)
jump_step[1:] = np.linalg.norm(X_eval[1:] - X_eval[:-1], axis=1)
jump_thr95 = float(np.percentile(jump_step, 95.0))

# Физический ориентир GTI-9 (9 операций бурения для локального Score)
gti9 = np.full(N, 8, dtype=np.int8)
on_bot = bp < 5.0
flow_on = flow > 1.5
rot_on = rot > 5.0
w_closed = wedge < 0.3

gti9[w_closed & (bp > 3000) & (~flow_on)] = 0   # устье / простой
gti9[w_closed & (bp <= 3000) & (~flow_on)] = 7  # клинья / наращивание
gti9[(~flow_on) & (bit_sl < -0.35) & (bp > 15) & (bp < 3210)] = 1  # СПО-спуск
gti9[(~flow_on) & (bit_sl >  0.35) & (bp > 15) & (bp < 3210)] = 2  # СПО-подъём
gti9[flow_on & (~on_bot) & (~rot_on)] = 6       # промывка без ротора
gti9[flow_on & (~on_bot) & rot_on] = 5          # проработка с вращением
gti9[flow_on & on_bot & (rot <= 15.0)] = 4      # медленное / слайд-бурение
gti9[flow_on & on_bot & (rot >  15.0)] = 3      # роторное бурение

# --- Метрики по формуле хакатона ---
def hungarian_macro_f1(y_true, y_pred):
    cm = confusion_matrix(y_true, y_pred, labels=range(9))
    r, c = linear_sum_assignment(-cm)
    mapping = {col: row for row, col in zip(r, c)}
    y_al = np.array([mapping.get(x, -1) for x in y_pred])
    return float(f1_score(y_true, y_al, average="macro", zero_division=0))

def boundary_f1(y_true, y_pred, tol=5):
    b_true = np.where(np.diff(y_true) != 0)[0]
    b_pred = np.where(np.diff(y_pred) != 0)[0]
    if len(b_true) == 0 and len(b_pred) == 0:
        return 1.0
    if len(b_true) == 0 or len(b_pred) == 0:
        return 0.0
    matched, used = 0, set()
    for b in b_pred:
        pos = np.searchsorted(b_true, b)
        best_idx, best_d = -1, tol + 1
        for cand in (pos - 1, pos):
            if 0 <= cand < len(b_true) and cand not in used:
                d = abs(int(b_true[cand]) - int(b))
                if d < best_d:
                    best_d, best_idx = d, cand
        if best_idx != -1:
            matched += 1
            used.add(best_idx)
    prec = matched / len(b_pred)
    rec = matched / len(b_true)
    return float(2 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0

def load_pred(path):
    if path.endswith(".npy"):
        arr = np.load(path)
        if arr.ndim == 2:
            arr = np.argmax(arr, axis=1)
        arr = arr.reshape(-1)
    else:
        tmp = pd.read_csv(path)
        if "ID" in tmp.columns:
            tmp = tmp.sort_values("ID")
        col = "operation" if "operation" in tmp.columns else tmp.columns[-1]
        arr = tmp[col].to_numpy()
    assert len(arr) == N, f"Неверная длина {len(arr)} != {N} ({path})"
    assert not pd.isna(arr).any(), f"Есть NaN ({path})"
    arr = arr.astype(np.int64)
    if arr.min() != 0:
        arr = arr - arr.min()
    return arr.astype(np.int8)

def eval_candidate(name, y):
    uniq = np.unique(y)
    ari = float(adjusted_rand_score(gti9, y))
    mf1 = hungarian_macro_f1(gti9, y)
    bf1 = boundary_f1(gti9, y, tol=5)
    score_proxy = 0.4 * ari + 0.4 * mf1 + 0.2 * bf1

    resid = np.zeros_like(X_eval)
    for k in uniq:
        m = (y == k)
        resid[m] = X_eval[m] - X_eval[m].mean(axis=0)
    phys_r2 = 1.0 - float(np.var(resid, axis=0).sum()) / tot_var

    ch = np.where(np.diff(y) != 0)[0] + 1
    lens = np.diff(np.r_[0, ch, N])
    hits = sum(jump_step[max(0, b - 3) : min(N, b + 4)].max() >= jump_thr95 for b in ch)
    jump_hit = (hits / len(ch) * 100.0) if len(ch) > 0 else 0.0

    min_cls = float(pd.Series(y).value_counts().min() / N * 100.0)
    short_cnt = int((lens <= 2).sum())

    warns = []
    if len(uniq) != 9:
        warns.append(f"КЛАССОВ={len(uniq)}")
    if min_cls < 1.5:
        warns.append(f"РЕДКИЙ<{min_cls:.2f}%")
    if short_cnt > 50:
        warns.append(f"ДРЕБЕЗГ={short_cnt}")

    return {
        "Model": name,
        "Proxy_Score": round(score_proxy, 4),
        "ARI_GTI9": round(ari, 4),
        "MacroF1_GTI9": round(mf1, 4),
        "BoundF1_GTI9": round(bf1, 4),
        "Phys_R2": round(phys_r2, 4),
        "Jump_Hit%": round(jump_hit, 1),
        "Segments": int(len(lens)),
        "Short<=2": short_cnt,
        "MinClass%": round(min_cls, 2),
        "Status": "OK" if not warns else " | ".join(warns),
    }

# --- Запуск сравнения ---
rows = []
for name, path in CANDIDATES.items():
    if os.path.exists(path):
        rows.append(eval_candidate(name, load_pred(path)))
    else:
        print(f"Пропущен (файл не найден): {name} -> {path}")

res = pd.DataFrame(rows)
if len(res) > 0:
    base_score = res.iloc[0]["Proxy_Score"]
    res["Delta_Score"] = (res["Proxy_Score"] - base_score).round(4)
    print(res.to_string(index=False))

    best_row = res.loc[res["Proxy_Score"].idxmax()]
    print(f"\nЛучшая локально: {best_row['Model']} (Proxy_Score={best_row['Proxy_Score']}, Jump_Hit={best_row['Jump_Hit%']}%, Status={best_row['Status']})")